package ch.lkmc.chessandcocoa.harness

import ch.lkmc.chessandcocoa.coach.decide.Difficulty
import ch.lkmc.chessandcocoa.coach.decide.PlanRole
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.async
import kotlinx.coroutines.awaitAll
import kotlinx.coroutines.runBlocking
import java.io.File
import java.time.LocalDate
import java.util.concurrent.ConcurrentLinkedQueue

/**
 * Desktop research harness for the decision experiments of concept Section
 * 16.7 (review Section D): E1 plan influence, E2 policy identity and early
 * refutation, E3 coverage, E4 desktop cost. Never shipped in the app.
 *
 * Usage: harness [--games N] [--difficulty GENTLE|STEADY|KEEN] [--workers W]
 *                [--plies P] [--out FILE] [--stockfish PATH]
 */
fun main(args: Array<String>) {
    val options = Options.parse(args)
    val stockfish = File(options.stockfish)
    require(stockfish.canExecute()) { "Stockfish not found at ${stockfish.path}; run scripts/build-stockfish-host.sh" }

    val seeds = ConcurrentLinkedQueue((1L..options.games.toLong()).toList())
    val games = runBlocking {
        (1..options.workers).map {
            async(Dispatchers.IO) {
                Worker(stockfish).use { worker ->
                    buildList {
                        while (true) {
                            val seed = seeds.poll() ?: break
                            add(simulate(worker, options.difficulty, seed, options.plies))
                            System.err.println("-- game $seed done (${size} on this worker)")
                        }
                    }
                }
            }
        }.awaitAll().flatten().sortedBy { it.record.seed }
    }

    val identity = runBlocking { Worker(stockfish).use { continuity(games, it.searcher) } }
    val report = Report.render(options, games, influence(games, seed = 1), identity)
    File(options.out).apply { parentFile?.mkdirs() }.writeText(report)
    println(report)
}

data class Options(
    val games: Int = 12,
    val difficulty: Difficulty = Difficulty.STEADY,
    val workers: Int = 6,
    val plies: Int = 80,
    val out: String = "docs/experiments/${LocalDate.now()}-steady.md",
    val stockfish: String = "build/stockfish-host/stockfish",
) {
    companion object {
        fun parse(args: Array<String>): Options {
            var options = Options()
            var outGiven = false
            args.toList().chunked(2).forEach { (key, value) ->
                options = when (key) {
                    "--games" -> options.copy(games = value.toInt())
                    "--difficulty" -> options.copy(difficulty = Difficulty.valueOf(value.uppercase()))
                    "--workers" -> options.copy(workers = value.toInt())
                    "--plies" -> options.copy(plies = value.toInt())
                    "--out" -> options.copy(out = value).also { outGiven = true }
                    "--stockfish" -> options.copy(stockfish = value)
                    else -> error("Unknown option $key")
                }
            }
            if (!outGiven) options = options.copy(out = "docs/experiments/${LocalDate.now()}-${options.difficulty.name.lowercase()}.md")
            return options
        }
    }
}

/** Markdown report; every number is measured in this run, nothing is estimated. */
object Report {

    fun render(options: Options, games: List<SimulatedGame>, influence: Influence, continuity: Continuity): String = buildString {
        val coverage = games.map(::coverage)
        val decisions = games.flatMap { g -> g.timings.filter { it.kind == StepKind.DECISION } }
        val assessments = games.flatMap { g -> g.timings.filter { it.kind == StepKind.ASSESSMENT } }

        appendLine("# Experiment run: ${options.difficulty.name.lowercase()} opponent")
        appendLine()
        appendLine("Generated by `harness` on ${LocalDate.now()}: ${games.size} games, at most ${options.plies} plies each, " +
            "opponent `${options.difficulty}` against the weakened-Stockfish learner proxy (not a model of human players). " +
            "Engine: host Stockfish 19, one thread per process, node-limited, hash cleared per search.")
        appendLine()

        appendLine("## E3. Coverage in ordinary games")
        appendLine()
        appendLine("| Per game | Median | Mean | Min | Max |")
        appendLine("|---|---|---|---|---|")
        row("Opponent decisions", coverage.map { it.decisions })
        row("Decisions where a template applied", coverage.map { it.templateApplies })
        row("Plan moves (any role)", coverage.map { it.planChosen })
        row("Plan introduced, decided or broke a tie", coverage.map { it.planDriven })
        row("Axis-B findings (not Unknown or no effect)", coverage.map { it.axisB })
        row("Plan events shown (Normal commentary)", coverage.map { it.planEventsShown })
        row("Human moves with tactical findings", coverage.map { it.tacticalFindings })
        row("Human moves with no feedback shown", coverage.map { it.silentMoves })
        appendLine()
        val shown = median(coverage.map { it.planEventsShown })
        appendLine("Decision rule (review E3): a median below 2 plan events per game calls for more frequent families. " +
            "Median here: $shown, so the rule is ${if (shown >= 2) "met" else "not met"}.")
        appendLine()

        appendLine("### Why plans were not chosen")
        appendLine()
        val considered = games.flatMap { g -> g.record.decisions.flatMap { it.considered } }
        appendLine("| Family | Outcome | Count |")
        appendLine("|---|---|---|")
        considered.groupingBy { it.family to it.outcome }.eachCount().toSortedMap(compareBy({ it.first }, { it.second })).forEach { (key, count) ->
            appendLine("| ${key.first} | ${key.second} | $count |")
        }
        val costs = considered.mapNotNull { it.costCp }
        if (costs.isNotEmpty()) {
            appendLine()
            appendLine("Shortfall of the best plan action when too costly (centipawns): p25 ${percentile(costs.map(Int::toLong), 25.0)}, " +
                "median ${percentile(costs.map(Int::toLong), 50.0)}, p75 ${percentile(costs.map(Int::toLong), 75.0)}.")
        }
        val blocks = considered.mapNotNull { it.assessment }.flatMap { it.refutations }.groupingBy { it.block?.name ?: it.outcome.name }.eachCount()
        appendLine()
        appendLine("Refuting probe branches by reason: " + blocks.entries.joinToString { "${it.key}: ${it.value}" }.ifEmpty { "none" } + ".")
        appendLine()

        appendLine("## E1. Plan influence and specificity")
        appendLine()
        appendLine("Eligible decisions (a template applied, at least two acceptable candidates): ${influence.eligible}.")
        appendLine()
        appendLine("| Plan role | Decisions | Share |")
        appendLine("|---|---|---|")
        PlanRole.entries.forEach { role ->
            val count = influence.roles[role] ?: 0
            appendLine("| $role | $count | ${percent(count, influence.eligible)} |")
        }
        val driven = listOf(PlanRole.INTRODUCED_CANDIDATE, PlanRole.DECISIVE, PlanRole.TIEBREAK).sumOf { influence.roles[it] ?: 0 }
        val compared = influence.progressWins + influence.progressTies + influence.progressLosses
        appendLine()
        appendLine("Plan introduced or decided the move: ${percent(driven, influence.eligible)} of eligible decisions (rule: at least 30%).")
        appendLine("Progress of the plan move against a random acceptable move: ${influence.progressWins} better, ${influence.progressTies} equal, " +
            "${influence.progressLosses} worse; better in ${percent(influence.progressWins, compared)} (rule: at least 70%).")
        appendLine()

        appendLine("## E2. Policy identity and early refutation (partial)")
        appendLine()
        appendLine("- Probe branches re-run live: ${continuity.probedBranches}; policy mismatches: ${continuity.policyMismatches} (must be 0).")
        appendLine("- Episodes adopted: ${continuity.adopted}; closed at the next own decision: ${continuity.deadOnArrival} " +
            "(${percent(continuity.deadOnArrival, continuity.adopted)}); within two: ${continuity.refutedWithinTwo} " +
            "(${percent(continuity.refutedWithinTwo, continuity.adopted)}); completed: ${continuity.completed}.")
        appendLine("- Not run: deeper offline rollouts (H = 3) and Maia-2 replies.")
        appendLine()

        appendLine("## E4. Cost on this desktop (not a phone)")
        appendLine()
        appendLine("| Step | p50 ms | p95 ms | max ms | p50 searches | p50 nodes |")
        appendLine("|---|---|---|---|---|---|")
        cost("Opponent decision", decisions)
        cost("Assessment of the human move (after warm-up)", assessments)
        appendLine()
        appendLine("Phone latency is unmeasured; run the same pipeline on target devices before relying on these numbers.")
    }

    private fun StringBuilder.row(label: String, values: List<Int>) {
        if (values.isEmpty()) return
        appendLine("| $label | ${median(values)} | ${"%.1f".format(values.average())} | ${values.min()} | ${values.max()} |")
    }

    private fun StringBuilder.cost(label: String, steps: List<StepTiming>) {
        if (steps.isEmpty()) return
        val millis = steps.map { it.millis }
        appendLine("| $label | ${percentile(millis, 50.0)} | ${percentile(millis, 95.0)} | ${millis.max()} | " +
            "${percentile(steps.map { it.searches.toLong() }, 50.0)} | ${percentile(steps.map { it.nodes }, 50.0)} |")
    }

    private fun percent(part: Int, whole: Int): String = if (whole == 0) "n/a" else "${(100.0 * part / whole).toInt()}%"
}
