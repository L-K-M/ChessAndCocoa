"""Convert the cburnett piece SVGs to Android VectorDrawables.

Handles exactly what the set uses: <svg viewBox>, nested <g> with inherited
presentation attributes, <path>, and <circle> (turned into two arcs).

Usage: python3 tools/pieces/svg2vector.py [--check]
  --check  exit 1 if a generated drawable is missing or out of date
"""
import pathlib
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCES = ROOT / "media-sources" / "pieces"
OUT = ROOT / "app" / "src" / "main" / "res" / "drawable"
SVG_NS = "{http://www.w3.org/2000/svg}"
INHERITED = ("fill", "fill-rule", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin")
DEFAULTS = {"fill": "#000", "fill-rule": "nonzero", "stroke": "none", "stroke-width": "1",
            "stroke-linecap": "butt", "stroke-linejoin": "miter"}


def color(value):
    """SVG colour -> Android #RRGGBB, or None for 'none'."""
    if value == "none":
        return None
    value = value.lstrip("#")
    if len(value) == 3:
        value = "".join(ch * 2 for ch in value)
    return "#FF" + value.upper()


def circle_path(cx, cy, r):
    return (f"M{cx - r},{cy}a{r},{r} 0 1,0 {2 * r},0a{r},{r} 0 1,0 {-2 * r},0z")


def walk(node, inherited, out):
    attrs = dict(inherited)
    for key in INHERITED:
        if key in node.attrib:
            attrs[key] = node.attrib[key]
    tag = node.tag.replace(SVG_NS, "")
    if tag == "path":
        out.append((node.attrib["d"], attrs))
    elif tag == "circle":
        cx, cy, r = (float(node.attrib[k]) for k in ("cx", "cy", "r"))
        out.append((circle_path(cx, cy, r), attrs))
    for child in node:
        walk(child, attrs, out)


def convert(svg_file):
    root = ET.parse(svg_file).getroot()
    _, _, width, height = root.attrib.get("viewBox", "0 0 45 45").split()
    paths = []
    walk(root, DEFAULTS, paths)
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        f"<!-- Generated by tools/pieces/svg2vector.py from media-sources/pieces/{svg_file.name}.",
        "     cburnett pieces by Colin M.L. Burnett, GPL-2.0-or-later. Do not edit. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{width}dp"',
        f'    android:height="{height}dp"',
        f'    android:viewportWidth="{width}"',
        f'    android:viewportHeight="{height}">',
    ]
    for d, attrs in paths:
        lines.append("    <path")
        fill = color(attrs["fill"])
        if fill:
            lines.append(f'        android:fillColor="{fill}"')
        if attrs["fill-rule"] == "evenodd":
            lines.append('        android:fillType="evenOdd"')
        stroke = color(attrs["stroke"])
        if stroke:
            lines.append(f'        android:strokeColor="{stroke}"')
            lines.append(f'        android:strokeWidth="{attrs["stroke-width"]}"')
            lines.append(f'        android:strokeLineCap="{attrs["stroke-linecap"]}"')
            lines.append(f'        android:strokeLineJoin="{attrs["stroke-linejoin"]}"')
        lines.append(f'        android:pathData="{d}" />')
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for svg_file in sorted(SOURCES.glob("*.svg")):
        target = OUT / f"piece_{svg_file.stem.lower()}.xml"
        text = convert(svg_file)
        if check:
            if not target.exists() or target.read_text() != text:
                stale.append(target.name)
            continue
        target.write_text(text)
    if stale:
        print("stale drawables: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
