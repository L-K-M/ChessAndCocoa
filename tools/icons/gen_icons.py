"""Regenerate the launcher icon and home artwork from media-sources/icon.png.

Adaptive icon: the master image is scaled to 80 of the 108 dp canvas so the
launcher mask never shows its square edges and the cup and knight stay
inside the visible circle; the background layer is the image's edge colour.

Usage: python3 tools/icons/gen_icons.py
Requires: Pillow.
"""
import pathlib

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[2]
MASTER = ROOT / "media-sources" / "icon.png"
RES = ROOT / "app" / "src" / "main" / "res"
CANVAS_DP = 108
CONTENT_DP = 80
DENSITIES = {"mdpi": 1.0, "hdpi": 1.5, "xhdpi": 2.0, "xxhdpi": 3.0, "xxxhdpi": 4.0}
HERO_PX = 512


def edge_colour(image):
    """Average colour of the image's outermost pixel ring."""
    width, height = image.size
    pixels = [image.getpixel((x, 0)) for x in range(width)] + [image.getpixel((x, height - 1)) for x in range(width)]
    channels = zip(*[p[:3] for p in pixels])
    return tuple(sum(c) // len(pixels) for c in channels)


def main():
    master = Image.open(MASTER).convert("RGB")
    for name, scale in DENSITIES.items():
        canvas_px = round(CANVAS_DP * scale)
        content_px = round(CONTENT_DP * scale)
        layer = Image.new("RGBA", (canvas_px, canvas_px), (0, 0, 0, 0))
        offset = (canvas_px - content_px) // 2
        layer.paste(master.resize((content_px, content_px), Image.LANCZOS), (offset, offset))
        folder = RES / f"mipmap-{name}"
        folder.mkdir(parents=True, exist_ok=True)
        layer.save(folder / "ic_launcher_foreground.png", optimize=True)

    red, green, blue = edge_colour(master)
    values = RES / "values"
    (values / "ic_launcher_background.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tools/icons/gen_icons.py. Do not edit. -->\n"
        f'<resources>\n    <color name="ic_launcher_background">#FF{red:02X}{green:02X}{blue:02X}</color>\n</resources>\n'
    )

    nodpi = RES / "drawable-nodpi"
    nodpi.mkdir(parents=True, exist_ok=True)
    master.resize((HERO_PX, HERO_PX), Image.LANCZOS).save(nodpi / "hero_cocoa.webp", quality=85)


if __name__ == "__main__":
    main()
